const SEVEN_DAYS = 7 * 24 * 60 * 60 * 1000;

/** 与原型一致：addedAt 在 7 天内标记 isNew */
export function markNewSites(sites: Site[], now = Date.now()): Site[] {
  return sites.map((site) => ({
    ...site,
    isNew: site.addedAt ? now - new Date(site.addedAt).getTime() < SEVEN_DAYS : false,
  }));
}
